"""Write dist/HydroComplete.bundle/PackageContents.xml from scripts/ribbon.json.

STRUCTURE RULE (the 1.9.0 "app is not working in Civil 3D" bug, Autodesk review
2026-11-14): each RuntimeRequirements must sit in its OWN <Components> element.
1.9.0 put four RuntimeRequirements + four ComponentEntry elements in one
<Components>; Civil 3D 2026 then loaded nothing ("Unknown command HC_ABOUT").
Split into one <Components> per runtime, the same files load and run.

Targets (1.10.0): Civil 3D 2025-2026 (R25.0-R25.1, .NET 8, Contents/) and Civil 3D
2027 (R26.0, .NET 10, Contents/net10/). Civil 3D 2024 (net48) was dropped in 1.10.0:
its .NET Framework polyfill DLLs were the Black Duck findings in two reviews.
The ribbon is a partial CUIX loaded for all three.
"""
import json
import os
import sys
from xml.sax.saxutils import quoteattr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
version = sys.argv[1]
spec = json.load(open(os.path.join(HERE, "ribbon.json"), encoding="utf-8"))
cmds = [b["cmd"] for p in spec for b in p["buttons"]]

DESC = ("Stormwater analysis driven straight from your Civil 3D drawing - Rational, "
        "SCS Tc, Manning, IDF with full formula transparency.")


def commands(indent):
    pad = " " * indent
    lines = [f'{pad}<Commands GroupName="HYDROCOMPLETE">']
    lines += [f'{pad}  <Command Local="{c}" Global="{c}" />' for c in cmds]
    lines.append(f"{pad}</Commands>")
    return "\n".join(lines)


def dotnet_block(comment, smin, smax, folder):
    mod = f"./Contents/{folder}HydroComplete.Civil3D.dll"
    eng = f"./Contents/{folder}HydroComplete.Engine.dll"
    return f"""  <!-- {comment} -->
  <Components Description={quoteattr(comment)}>
    <RuntimeRequirements OS="Win64" Platform="Civil3D" SeriesMin="{smin}" SeriesMax="{smax}" />
    <ComponentEntry AppName="HYDROCOMPLETE"
                    Version="{version}"
                    AppDescription="HydroComplete stormwater analysis"
                    AppType=".NET"
                    ModuleName="{mod}"
                    LoadOnAutoCADStartup="True"
                    LoadOnRequest="True">
{commands(6)}
      <AssemblyMappings>
        <AssemblyMapping Name="HydroComplete.Engine" Path="{eng}" />
      </AssemblyMappings>
    </ComponentEntry>
  </Components>
"""


xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by scripts/gen-packagecontents.py from scripts/ribbon.json. Do not hand-edit.
  One RuntimeRequirements per <Components> element (see the script header for why).
    Civil 3D 2025 = R25.0, 2026 = R25.1 (.NET 8, Contents/)
    Civil 3D 2027 = R26.0 (.NET 10, Contents/net10/)
-->
<ApplicationPackage SchemaVersion="1.0"
                    AppVersion="{version}"
                    Name="HydroComplete"
                    Description={quoteattr(DESC)}
                    Author="HydroComplete LLC"
                    ProductCode="{{8d07b4c8-06cb-497d-832a-dcb5b095d9fa}}"
                    HelpFile="./Help/index.html"
                    OnlineDocumentation="https://hydrocomplete.com/civil3d"
                    Icon="./Contents/PackageIcon.png">

  <CompanyDetails Name="HydroComplete LLC"
                  Url="https://hydrocomplete.com/civil3d"
                  Email="support@hydrocomplete.com" />

{dotnet_block("Civil 3D 2025 and 2026 (.NET 8)", "R25.0", "R25.1", "")}
{dotnet_block("Civil 3D 2027 (.NET 10)", "R26.0", "R26.0", "net10/")}
  <!-- Ribbon: partial CUIX with the HydroComplete tab and embedded button icons -->
  <Components Description="HydroComplete ribbon">
    <RuntimeRequirements OS="Win64" Platform="Civil3D" SeriesMin="R25.0" SeriesMax="R26.0" />
    <ComponentEntry AppName="HydroCompleteRibbon"
                    Version="{version}"
                    AppDescription="HydroComplete ribbon tab"
                    AppType="CUIX"
                    ModuleName="./Contents/HydroComplete.cuix" />
  </Components>

</ApplicationPackage>
"""
out = os.path.join(ROOT, "dist", "HydroComplete.bundle", "PackageContents.xml")
open(out, "w", encoding="utf-8", newline="\r\n").write(xml)
print(f"wrote {out}: {len(cmds)} commands, AppVersion {version}")
